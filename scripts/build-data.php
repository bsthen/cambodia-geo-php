<?php

declare(strict_types=1);

/**
 * Converts the original MEF CSV files in data/ into PHP array files in src/Data/ (committed to Git,
 * because Composer installs the repository as it is and cannot run a build step), and writes
 * src/Meta.php with the data year. Run: composer build-data
 *
 * Yearly update: replace the four CSV files in data/ (keep the original MEF names, e.g.
 * CambodiaProvinceList2026.csv) and delete the old-year files. The year is detected from the file names.
 */

$root = dirname(__DIR__);
require_once $root . '/src/Internal/Text.php';
$dataDir = $root . '/data';
$outDir = $root . '/src/Data';

$specs = [
    ['key' => 'provinces', 'level' => 'province', 'prefix' => 'CambodiaProvinceList', 'parents' => []],
    ['key' => 'districts', 'level' => 'district', 'prefix' => 'CambodiaDistrictList', 'parents' => ['province_code']],
    ['key' => 'communes', 'level' => 'commune', 'prefix' => 'CambodiaCommuneList', 'parents' => ['province_code', 'district_code']],
    ['key' => 'villages', 'level' => 'village', 'prefix' => 'CambodiaVillagesList', 'parents' => ['province_code', 'district_code', 'commune_code']],
];

function fail(string $message): never
{
    fwrite(STDERR, "build-data: {$message}\n");
    exit(1);
}

/** Quote a string as a PHP single-quoted literal. */
function q(string $value): string
{
    return "'" . strtr($value, ['\\' => '\\\\', "'" => "\\'"]) . "'";
}

$files = scandir($dataDir) ?: [];
$years = [];
$chosen = [];
foreach ($specs as $spec) {
    $matches = [];
    foreach ($files as $file) {
        if (preg_match('/^' . $spec['prefix'] . '(\d{4})\.csv$/', $file, $m) === 1) {
            $matches[] = [$file, $m[1]];
        }
    }
    if (count($matches) === 0) {
        fail("no file named {$spec['prefix']}<year>.csv found in data/");
    }
    if (count($matches) > 1) {
        fail("several files for {$spec['prefix']}: " . implode(', ', array_column($matches, 0)) . '. Delete the old-year file(s).');
    }
    $years[$matches[0][1]] = true;
    $chosen[] = $spec + ['file' => $matches[0][0]];
}
if (count($years) !== 1) {
    fail('the four CSV files must have the same year, found: ' . implode(', ', array_keys($years)));
}
$dataYear = (int) array_key_first($years);

if (!is_dir($outDir) && !mkdir($outDir, 0777, true) && !is_dir($outDir)) {
    fail("cannot create {$outDir}");
}

$counts = [];
foreach ($chosen as $spec) {
    $handle = fopen($dataDir . '/' . $spec['file'], 'rb');
    if ($handle === false) {
        fail("cannot open {$spec['file']}");
    }
    $header = fgetcsv($handle, 0, ',', '"', '');
    if ($header === false) {
        fail("{$spec['file']} is empty");
    }
    $header = array_map(static fn ($h) => trim((string) $h), $header);
    $header[0] = ltrim($header[0], "\xEF\xBB\xBF"); // UTF-8 BOM
    $own = ["{$spec['level']}_code", "{$spec['level']}_kh", "{$spec['level']}_en"];
    $missing = array_diff(array_merge($own, $spec['parents']), $header);
    if ($missing) {
        fail("{$spec['file']} is missing column(s): " . implode(', ', $missing));
    }
    $pos = array_flip($header);

    // Row layout: [code, nameKh, nameEn, ...parent codes]. CSV row order is preserved exactly.
    // 'children' maps the canonical path of the parent ("17/1702") to the row numbers below it, so that
    // the library does not have to build any index at run time.
    $lines = [];
    $children = [];
    while (($row = fgetcsv($handle, 0, ',', '"', '')) !== false) {
        if ($row === [null]) {
            continue; // blank line
        }
        $cell = static fn (string $column): string => trim((string) ($row[$pos[$column]] ?? ''));
        $code = $cell($own[0]);
        if ($code === '') {
            continue; // skip blank / malformed lines
        }
        $values = [$code, $cell($own[1]), $cell($own[2])];
        foreach ($spec['parents'] as $parent) {
            $values[] = $cell($parent);
        }
        $parentKey = implode('/', array_map(
            static fn (string $c): string => \CambodiaGeo\Internal\Text::codeKey($c),
            array_slice($values, 3),
        ));
        $children[$parentKey][] = count($lines);
        $lines[] = '[' . implode(',', array_map('q', $values)) . '],';
    }
    fclose($handle);
    $counts[$spec['key']] = count($lines);

    $childLines = [];
    foreach ($children as $key => $rows) {
        $childLines[] = q((string) $key) . '=>[' . implode(',', $rows) . '],';
    }
    $source = "<?php\n\n// AUTO-GENERATED by scripts/build-data.php from data/{$spec['file']}. Do not edit.\n\n"
        . "declare(strict_types=1);\n\nreturn [\n'rows' => [\n" . implode("\n", $lines) . "\n],\n"
        . "'children' => [\n" . implode("\n", $childLines) . "\n],\n];\n";
    file_put_contents($outDir . "/{$spec['key']}.php", $source);
}

$meta = "<?php\n\n// AUTO-GENERATED by scripts/build-data.php. Do not edit.\n\n"
    . "declare(strict_types=1);\n\nnamespace CambodiaGeo;\n\n"
    . "/** Facts about the bundled dataset. */\nfinal class Meta\n{\n"
    . "    /** Year of the bundled MEF dataset. */\n    public const DATA_YEAR = {$dataYear};\n}\n";
file_put_contents($root . '/src/Meta.php', $meta);

echo "build-data: {$dataYear} data -> "
    . implode(', ', array_map(static fn ($k, $v) => "{$v} {$k}", array_keys($counts), $counts)) . "\n";
